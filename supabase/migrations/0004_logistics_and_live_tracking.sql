alter table public.profiles drop constraint if exists profiles_account_type_check;
alter table public.profiles
  add constraint profiles_account_type_check
  check (account_type in ('buyer', 'seller', 'both', 'logistics'));

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare requested_type text;
begin
  requested_type := new.raw_user_meta_data ->> 'account_type';
  if requested_type is null or requested_type not in ('buyer', 'seller', 'both', 'logistics') then
    requested_type := 'buyer';
  end if;
  insert into public.profiles (id, full_name, account_type)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''), requested_type)
  on conflict (id) do nothing;
  return new;
end;
$$;

create table if not exists public.transport_locations (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.transport_requests(id) on delete cascade,
  provider_id uuid not null references public.transport_profiles(id) on delete cascade,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_m double precision,
  recorded_at timestamptz not null default now()
);
create index if not exists idx_transport_locations_trip_time
  on public.transport_locations(request_id, recorded_at desc);
alter table public.transport_locations enable row level security;

drop policy if exists "Trip participants can view live locations" on public.transport_locations;
create policy "Trip participants can view live locations"
on public.transport_locations for select to authenticated
using (
  exists (
    select 1 from public.transport_requests tr
    where tr.id = transport_locations.request_id
      and (
        tr.requester_id = (select auth.uid())
        or exists (
          select 1 from public.transport_profiles tp
          where tp.id = transport_locations.provider_id and tp.user_id = (select auth.uid())
        )
      )
  )
);

drop policy if exists "Assigned providers can send trip locations" on public.transport_locations;
create policy "Assigned providers can send trip locations"
on public.transport_locations for insert to authenticated
with check (
  exists (
    select 1 from public.transport_profiles tp
    join public.transport_requests tr on tr.provider_id = tp.id
    where tp.id = transport_locations.provider_id
      and tp.user_id = (select auth.uid())
      and tr.id = transport_locations.request_id
      and tr.status in ('accepted', 'in_transit')
  )
);

drop policy if exists "Requesters can update quote decisions" on public.transport_quotes;
create policy "Requesters can update quote decisions"
on public.transport_quotes for update to authenticated
using (exists (
  select 1 from public.transport_requests tr
  where tr.id = transport_quotes.request_id and tr.requester_id = (select auth.uid())
))
with check (exists (
  select 1 from public.transport_requests tr
  where tr.id = transport_quotes.request_id and tr.requester_id = (select auth.uid())
));

drop policy if exists "Assigned providers can update delivery status" on public.transport_requests;
create policy "Assigned providers can update delivery status"
on public.transport_requests for update to authenticated
using (provider_id is not null and exists (
  select 1 from public.transport_profiles tp
  where tp.id = transport_requests.provider_id and tp.user_id = (select auth.uid())
))
with check (provider_id is not null and exists (
  select 1 from public.transport_profiles tp
  where tp.id = transport_requests.provider_id and tp.user_id = (select auth.uid())
));

